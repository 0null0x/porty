#!/usr/bin/env python3
"""Generate tcg/wasm32-tci-calls.h for patch 0015 (QEMU-Wasm's TCI calls
helpers without libffi).

TCG passes helpers only i32 (also pointers) and i64 values and gets back
nothing, an i32 or an i64 (or an Int128, which stays with libffi).  A
WebAssembly call_indirect needs the callee's exact signature, so the
interpreter dispatches on a code for it:

    code = return kind << 10 | number of arguments << 7 | 64-bit argument mask

(return kind 0 void, 1 i32, 2 i64; bit i of the mask: argument i is 64-bit)
and calls the helper through a pointer of that type.  This prints every
code for up to MAX_CALL_IARGS (7) arguments; the output is in patch 0015.

usage: build/gen-tci-calls.py > tcg/wasm32-tci-calls.h
"""
import sys

MAX_ARGS = 7
RET = {0: 'V_', 1: 'W_', 2: 'X_'}


def main() -> None:
    out = sys.stdout
    out.write("""/*
 * Porty: TCI's helper calls by signature, without libffi.
 * Generated by Porty's build/gen-tci-calls.py; do not edit.
 *
 * code = return kind << 10 | number of arguments << 7 | 64-bit argument mask
 * (return kind 0 void, 1 i32, 2 i64; bit i: argument i is 64-bit).
 * Arguments are read through av[i] as libffi would; the result goes to ret
 * as libffi would put it there.  Returns false for a code not listed.
 *
 * SPDX-License-Identifier: GPL-2.0-or-later
 */
#define PORTY_TCI_CODE(r, n, mask) ((r) << 10 | (n) << 7 | (mask))
#define PORTY_TCI_MAX_ARGS %d

/*
 * The code of a libffi signature, or -1 when the switch has none for it:
 * Int128 (a struct), floating point, more than PORTY_TCI_MAX_ARGS
 * arguments.  Pointers are i32 on wasm32 (elsewhere they are left to libffi).
 */
static int porty_tci_code(const ffi_cif *cif)
{
    unsigned n = cif->nargs, i;
    int r, mask = 0;

    if (n > PORTY_TCI_MAX_ARGS) {
        return -1;
    }
    switch (cif->rtype->type) {
    case FFI_TYPE_VOID:
        r = 0;
        break;
    case FFI_TYPE_POINTER:
        if (sizeof(void *) != 4) {
            return -1;
        }
        /* fall through */
    case FFI_TYPE_INT:
    case FFI_TYPE_UINT32:
    case FFI_TYPE_SINT32:
        r = 1;
        break;
    case FFI_TYPE_UINT64:
    case FFI_TYPE_SINT64:
        r = 2;
        break;
    default:
        return -1;
    }
    for (i = 0; i < n; i++) {
        switch (cif->arg_types[i]->type) {
        case FFI_TYPE_POINTER:
            if (sizeof(void *) != 4) {
                return -1;
            }
            break;
        case FFI_TYPE_INT:
        case FFI_TYPE_UINT32:
        case FFI_TYPE_SINT32:
            break;
        case FFI_TYPE_UINT64:
        case FFI_TYPE_SINT64:
            mask |= 1 << i;
            break;
        default:
            return -1;
        }
    }
    return PORTY_TCI_CODE(r, (int)n, mask);
}

/*
 * Call f with the arguments av[0..n) point to and put its result where
 * libffi would (4 bytes at ret for an i32, 8 for an i64); false if the
 * switch has no case for the code.
 */
static bool porty_tci_call_direct(int code, void *f, void *ret, void **av)
{
#define I_ uint32_t
#define J_ uint64_t
#define a_(i) (*(I_ *)av[i])
#define b_(i) (*(J_ *)av[i])
#define V_(...) ((void (*)(__VA_ARGS__))f)
#define W_(...) *(I_ *)ret = ((I_ (*)(__VA_ARGS__))f)
#define X_(...) *(J_ *)ret = ((J_ (*)(__VA_ARGS__))f)
    switch (code) {
""" % MAX_ARGS)
    count = 0
    for r in (0, 1, 2):
        for n in range(MAX_ARGS + 1):
            for mask in range(1 << n):
                params = ', '.join('J_' if mask >> i & 1 else 'I_' for i in range(n)) or 'void'
                args = ', '.join(f'b_({i})' if mask >> i & 1 else f'a_({i})' for i in range(n))
                code = r << 10 | n << 7 | mask
                out.write(f'    case {code}: {RET[r]}({params})({args}); break;\n')
                count += 1
    out.write("""    default:
        return false;
    }
    return true;
#undef I_
#undef J_
#undef a_
#undef b_
#undef V_
#undef W_
#undef X_
}
""")
    print(f'{count} signatures', file=sys.stderr)


if __name__ == '__main__':
    main()
